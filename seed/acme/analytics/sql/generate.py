"""Writes shop.sql: a small, fictional order database for testing analytics on a live SQL source
(PostgreSQL or MySQL, docs/analytics-sql-sources.md). Deterministic: the same file every run.

    python seed/acme/analytics/sql/generate.py

shop.sql creates the tables in a schema (PostgreSQL) or database (MySQL) named `shop`, which
must exist, and fills them. It uses only SQL both accept. `hr.salaries` is outside the shop
schema on purpose: a source whose schema allow-list is `shop` must never reach it. The tests
(tests/integration/test_analytics_sources.py) and the eval items in
evals/datasets/analytics_sql.jsonl rely on these exact rows.
"""

import random
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
DAN, DIEGO = "dan@acme.test", "diego.alvarez@acme.test"
CUSTOMERS = [
    # id, name, region, segment, account owner
    ("S01", "Alder Outfitters", "North", "Retail", DAN),
    ("S02", "Birch Supply Co", "South", "Wholesale", DIEGO),
    ("S03", "Cedar Online", "West", "Online", DIEGO),
    ("S04", "Dune Traders", "East", "Wholesale", DAN),
    ("S05", "Elm Street Stores", "North", "Retail", DIEGO),
    ("S06", "Fjord Market", "North", "Online", DIEGO),
    ("S07", "Granite Goods", "South", "Retail", DAN),
    ("S08", "Harbor Wholesale", "East", "Wholesale", DIEGO),
    ("S09", "Iris Direct", "West", "Online", DIEGO),
    ("S10", "Juniper Home", "West", "Retail", DAN),
]
STATUSES = ["paid"] * 6 + ["refunded", "open"]
CHANNELS = ["web", "partner", "direct"]


def orders() -> list[tuple[str, str, date, str, str, str]]:
    rng = random.Random(2026)
    rows: list[tuple[str, str, date, str, str, str]] = []
    for month in range(1, 10):
        for customer in CUSTOMERS:
            for _ in range(rng.choice([0, 1, 1, 2])):
                day = rng.randint(1, 28)
                amount = f"{rng.randint(500, 20_000)}.{rng.choice(['00', '50', '25', '90'])}"
                order_id = f"O{len(rows) + 1:04d}"
                status = rng.choice(STATUSES)
                rows.append(
                    (
                        order_id,
                        customer[0],
                        date(2026, month, day),
                        status,
                        rng.choice(CHANNELS),
                        amount,
                    )
                )
    return rows


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    lines = [
        "-- Generated by generate.py: a fictional order database for analytics on a SQL source.",
        "-- Run it in an empty schema (PostgreSQL) or database (MySQL) named shop, and hr.",
        "CREATE TABLE shop.customers (",
        "  customer_id VARCHAR(8) PRIMARY KEY,",
        "  name VARCHAR(100) NOT NULL,",
        "  region VARCHAR(20) NOT NULL,",
        "  segment VARCHAR(20) NOT NULL,",
        "  account_owner VARCHAR(100) NOT NULL",
        ");",
        "CREATE TABLE shop.orders (",
        "  order_id VARCHAR(10) PRIMARY KEY,",
        "  customer_id VARCHAR(8) NOT NULL,",
        "  order_date DATE NOT NULL,",
        "  status VARCHAR(12) NOT NULL,",
        "  channel VARCHAR(12) NOT NULL,",
        "  amount_eur NUMERIC(12, 2) NOT NULL",
        ");",
        "-- In the shop schema but not in the semantic model: never queryable.",
        "CREATE TABLE shop.internal_notes (note_id INTEGER PRIMARY KEY, note VARCHAR(200));",
        "INSERT INTO shop.internal_notes VALUES (1, 'CANARY-NOTES-7731: not in the model');",
        "-- Outside the shop schema: not in the source's allow-list.",
        "CREATE TABLE hr.salaries (employee VARCHAR(100) PRIMARY KEY, salary_eur INTEGER);",
        "INSERT INTO hr.salaries VALUES ('CANARY-SALARY-5520', 123456);",
    ]
    values = [
        f"  ({', '.join(quote(v) for v in customer)})" for customer in CUSTOMERS
    ]
    lines.append("INSERT INTO shop.customers VALUES\n" + ",\n".join(values) + ";")
    values = [
        f"  ({quote(o)}, {quote(c)}, DATE '{d.isoformat()}', {quote(s)}, {quote(ch)}, {a})"
        for o, c, d, s, ch, a in orders()
    ]
    lines.append("INSERT INTO shop.orders VALUES\n" + ",\n".join(values) + ";")
    (HERE / "shop.sql").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
